"""Read the text out of a document, page by page, so it can be searched.

WHY. "Ask the documents" matched file names and AI summaries, and 11 of 5,336
documents had a summary. What the files actually say was stored nowhere a
search could reach. This reads it locally — PyMuPDF for PDFs, the existing
`doc_text` readers for Word, Excel and plain text — and keeps it per page in
`document_text_pages`, where Postgres full-text search finds it. No model call,
no new service, no per-file cost.

WHAT IS QUEUED. Only file types that can carry text. A photo or a video never
gets a row, so it never sits in a queue it can never leave and never shows up
as "couldn't be read" when nobody expected it to be read.

WHO RUNS IT. The AI worker, and only when it has no AI job to run — reading a
1,500-file backlog must never put a scope or an estimate behind it. One file
per turn of the loop, claimed with SKIP LOCKED like an AI job.

WHAT A SCAN LOOKS LIKE. A PDF whose pages carry no text layer (a scan, or a
drawing exported as an image) is `no_text`, with that reason in words. It is
not a failure of this code and it is not searchable; saying so is the point.
"""
from __future__ import annotations

import logging
import os
import re
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any
from uuid import UUID

from sqlalchemy import text as _T
from sqlalchemy.orm import Session

from app.models.document import Document
from app.models.document_text import DocumentText

logger = logging.getLogger("brio.document_text")

PDF_EXTS = (".pdf",)

#: Above this the file is not fetched at all. Two PDFs in the corpus are larger;
#: they are reported as too large rather than risking the worker's memory.
MAX_BYTES = 60 * 1024 * 1024
#: A 2,000-page PDF is a document set, not a document; the rest is announced.
MAX_PAGES = 2_000
#: Per page. Was 20,000: the 880 Harbour trial cut a structural general-notes
#: sheet off at that, losing real notes. A dense notes sheet runs past 20k;
#: 200k stays well inside Postgres's 1 MB tsvector limit.
MAX_PAGE_CHARS = 200_000
#: Per document, across all pages.
MAX_DOC_CHARS = 5_000_000
#: A file is a scan unless at least one page has this many real characters —
#: a scanned set often carries a stray stamp or page number and nothing else.
#: Short pages are still kept when the file as a whole has text: a drawing
#: sheet may say little more than "A-201 ROOF PLAN".
MIN_PAGE_CHARS = 20
#: Below this a page is noise ("3", "-") and is not stored.
MIN_KEEP_CHARS = 3

#: A claimed file that has not finished in this long was abandoned by a worker
#: that stopped; it goes back to the queue.
STALE_AFTER_MINUTES = 15
#: ...at most this many times, then it is failed with a reason.
MAX_ATTEMPTS = 3

#: Generated by the app from other rows; re-reading it would index the index.
_SKIP_CATEGORIES = {"project_index"}

NO_TEXT_PDF = (
    "No text layer — this looks like a scan, or a drawing saved as an image. "
    "Its words can't be searched without OCR."
)
NO_TEXT_FILE = "The file has no text in it."


def searchable_exts() -> tuple[str, ...]:
    from app.services import doc_text

    return PDF_EXTS + doc_text.EXTRACTABLE_EXTS


def is_readable_type(filename: str | None) -> bool:
    return os.path.splitext(filename or "")[1].lower() in searchable_exts()


@dataclass
class PageResult:
    status: str  # ok | no_text | failed
    pages: list[tuple[int, str]] = field(default_factory=list)
    page_count: int = 0
    truncated: bool = False
    error: str | None = None

    @property
    def char_count(self) -> int:
        return sum(len(t) for _, t in self.pages)


_SPACES = re.compile(r"[ \t\f\v\r]+")
_BLANK_LINES = re.compile(r"\n\s*\n+")


def _clean(text: str) -> str:
    # Postgres text cannot hold NUL, and PDFs emit it.
    text = text.replace("\x00", "")
    text = _SPACES.sub(" ", text)
    return _BLANK_LINES.sub("\n", text).strip()


def _from_pdf(data: bytes) -> PageResult:
    import fitz  # PyMuPDF

    try:
        pdf = fitz.open(stream=data, filetype="pdf")
    except Exception as exc:  # noqa: BLE001
        return PageResult(status="failed", error=f"Could not be opened as a PDF ({exc}).")
    try:
        if pdf.needs_pass:
            return PageResult(status="failed", error="The PDF is password-protected.")
        out = PageResult(status="ok", page_count=len(pdf))
        total, substantial = 0, False
        for i in range(min(len(pdf), MAX_PAGES)):
            text = _clean(pdf[i].get_text("text"))
            real = len(text.replace(" ", "").replace("\n", ""))
            if real < MIN_KEEP_CHARS:
                continue
            substantial = substantial or real >= MIN_PAGE_CHARS
            if len(text) > MAX_PAGE_CHARS:
                text, out.truncated = text[:MAX_PAGE_CHARS], True
            if total + len(text) > MAX_DOC_CHARS:
                out.truncated = True
                break
            total += len(text)
            out.pages.append((i + 1, text))
        if len(pdf) > MAX_PAGES:
            out.truncated = True
        if not substantial:
            return PageResult(status="no_text", page_count=len(pdf), error=NO_TEXT_PDF)
        return out
    finally:
        pdf.close()


def extract_pages(filename: str, data: bytes) -> PageResult:
    """The searchable text of a file, page by page, or a stated reason there is none."""
    ext = os.path.splitext(filename or "")[1].lower()
    if ext in PDF_EXTS:
        return _from_pdf(data)

    from app.services import doc_text

    got = doc_text.extract(filename, data, doc_text.SEARCH_LIMITS)
    if got.error:
        return PageResult(status="failed", error=got.error[:1].upper() + got.error[1:] + ".")
    text = _clean(got.text)
    if not text:
        return PageResult(status="no_text", page_count=1, error=NO_TEXT_FILE)
    # A Word file or a spreadsheet has no pages a person could be sent to;
    # the whole of it is page 1.
    return PageResult(status="ok", pages=[(1, text)], page_count=1, truncated=got.truncated)


# ── queue ─────────────────────────────────────────────────────────────────


def queue_document_text(db: Session, document: Document, *, force: bool = False) -> bool:
    """Put a document in the queue to be read. Caller commits.

    Returns False, writing nothing, for a file type that cannot carry text.
    Without ``force`` a document already read (or already waiting) is left as
    it is; with it, the document goes back to waiting and is read again.
    """
    if document.size_bytes is None or not is_readable_type(document.filename):
        return False
    if document.category in _SKIP_CATEGORIES:
        return False
    row = db.get(DocumentText, document.id)
    if row is None:
        db.add(DocumentText(document_id=document.id, project_id=document.project_id,
                            status="pending"))
        return True
    if not force or row.status == "running":
        return row.status == "pending"
    row.status, row.error, row.attempts, row.claimed_at = "pending", None, 0, None
    return True


def claim_next(db: Session) -> UUID | None:
    """Claim the oldest waiting document and commit the claim.

    A row left `running` past STALE_AFTER_MINUTES belonged to a worker that
    stopped mid-file. It is claimed again, up to MAX_ATTEMPTS, and after that it
    is failed with a reason instead of being retried forever — a PDF that kills
    the worker every time would otherwise kill it every time.
    """
    db.execute(_T(f"""
        UPDATE document_texts
           SET status = 'failed', updated_at = now(),
               error = 'Reading it stopped part-way {MAX_ATTEMPTS} times; it is probably too large or damaged.'
         WHERE status = 'running'
           AND claimed_at < now() - interval '{STALE_AFTER_MINUTES} minutes'
           AND attempts >= {MAX_ATTEMPTS}
    """))
    row = db.execute(_T(f"""
        SELECT document_id FROM document_texts
         WHERE status = 'pending'
            OR (status = 'running'
                AND claimed_at < now() - interval '{STALE_AFTER_MINUTES} minutes')
         ORDER BY created_at
         LIMIT 1
         FOR UPDATE SKIP LOCKED
    """)).first()
    if row is None:
        db.commit()
        return None
    db.execute(_T("""
        UPDATE document_texts
           SET status = 'running', attempts = attempts + 1, claimed_at = now(), updated_at = now()
         WHERE document_id = :d
    """), {"d": row[0]})
    db.commit()
    return row[0]


def _finish(db: Session, row: DocumentText, result: PageResult) -> None:
    db.execute(_T("DELETE FROM document_text_pages WHERE document_id = :d"),
               {"d": row.document_id})
    if result.pages:
        db.execute(_T("""
            INSERT INTO document_text_pages (document_id, page_no, project_id, text)
            VALUES (:d, :n, :p, :t)
        """), [{"d": row.document_id, "n": n, "p": row.project_id, "t": t}
               for n, t in result.pages])
    row.status = result.status
    row.error = result.error
    row.page_count = result.page_count or None
    row.pages_with_text = len(result.pages)
    row.char_count = result.char_count
    row.truncated = result.truncated
    row.extracted_at = datetime.now(timezone.utc)
    db.commit()


def read_document(db: Session, document_id: UUID, *, fetch=None) -> str:
    """Read one claimed document and store its pages. Returns the final status.

    ``fetch`` is the R2 reader, injectable so tests need no bucket.
    """
    if fetch is None:
        from app.services.r2 import get_bytes as fetch

    row = db.get(DocumentText, document_id)
    if row is None:
        return "gone"
    doc = db.get(Document, document_id)
    if doc is None:  # pragma: no cover — the FK cascades; belt and braces
        db.delete(row)
        db.commit()
        return "gone"
    if doc.size_bytes and doc.size_bytes > MAX_BYTES:
        _finish(db, row, PageResult(
            status="too_large",
            error=f"Larger than {MAX_BYTES // (1024 * 1024)} MB, so it was not read."))
        return row.status
    try:
        data = fetch(doc.r2_key)
    except Exception as exc:  # noqa: BLE001
        logger.warning("document_text: could not fetch %s: %s", document_id, exc)
        _finish(db, row, PageResult(status="failed",
                                    error="The file could not be fetched from storage."))
        return row.status
    try:
        result = extract_pages(doc.filename, data)
    except Exception as exc:  # noqa: BLE001 — one bad file must not stop the queue
        logger.exception("document_text: reading %s failed", document_id)
        result = PageResult(status="failed", error=f"Reading the file failed ({exc}).")
    _finish(db, row, result)
    return row.status


def run_one() -> bool:
    """Claim and read at most one document. Returns True if one was read."""
    from app.db import SessionLocal

    with SessionLocal() as db:
        document_id = claim_next(db)
        if document_id is None:
            return False
        status = read_document(db, document_id)
    logger.info("document_text: %s -> %s", document_id, status)
    return True


# ── status for the Documents page ─────────────────────────────────────────


def project_text_status(db: Session, project_id: UUID) -> list[dict[str, Any]]:
    rows = db.execute(_T("""
        SELECT document_id, status, page_count, pages_with_text, truncated, error
          FROM document_texts WHERE project_id = :p
    """), {"p": project_id}).mappings().all()
    return [{**r, "document_id": str(r["document_id"])} for r in rows]


def coverage(db: Session, project_ids: list[UUID]) -> dict[str, int]:
    """How much of the readable corpus has been read, so a search can say
    what it covered instead of implying it covered everything."""
    if not project_ids:
        return {}
    exts = searchable_exts()
    ext_sql = " OR ".join(f"lower(d.filename) LIKE '%{e}'" for e in exts)
    row = db.execute(_T(f"""
        SELECT count(*)                                         AS readable,
               count(*) FILTER (WHERE t.status = 'ok')          AS searchable,
               count(*) FILTER (WHERE t.status IN ('pending','running')) AS waiting,
               count(*) FILTER (WHERE t.status IN ('no_text','too_large','failed')) AS unreadable,
               count(*) FILTER (WHERE t.document_id IS NULL)    AS not_queued
          FROM documents d
     LEFT JOIN document_texts t ON t.document_id = d.id
         WHERE d.project_id = ANY(:pids) AND d.archived = false
           AND d.size_bytes IS NOT NULL AND ({ext_sql})
           AND d.category <> 'project_index'
    """), {"pids": [str(p) for p in project_ids]}).mappings().first()
    return dict(row) if row else {}
