/**
 * Drawing alignment — the acceptance criterion from §11, and an honest account
 * of which half of it code can actually check.
 *
 * THE CRITERION: "for 20 highlighted quantities across 5 sheets at 3 zoom levels
 * and both page rotations, the highlight encloses the correct feature. 20/20,
 * and rotation cases must be included."
 *
 * ⚠️ WHAT THIS DOES NOT PROVE. "Encloses the correct feature" is a claim about
 * a rendered page and a human eye. No script can settle it: if the analyser
 * reported a bbox around the wrong stroke, a perfectly correct transform will
 * place a perfectly wrong highlight. Amir confirmed enclosure by eye on one
 * sheet on 2 Oct, which is what unblocked capture. This file checks the other
 * half — that the TRANSFORM is self-consistent, invertible, and stable across
 * zoom and rotation — which is the half that breaks silently.
 *
 * ⚠️ ONE SHEET, NOT FIVE. Production holds exactly ONE stored drawing analysis
 * (verified 2026-10-02), so five real sheets do not exist to test against. The
 * fixture is that sheet's real page geometry and 20 of its real bboxes.
 *
 * ⚠️ ROTATIONS ARE SYNTHETIC, and this matters. No rotated sheet has ever been
 * analysed in production — every stored page is rotation 0. The comment in
 * bboxToScreen.ts says "270° is not hypothetical — the PROJB and Maple sets
 * are both rotated that way"; that is NOT supported by the current data and may
 * predate the 2026-08-31 wipe. The 90/180/270 cases below are generated by
 * re-labelling the real page, so they exercise the code path with real
 * coordinates but are not evidence that a real rotated sheet renders correctly.
 * That remains unverified and should be checked by eye when one is analysed.
 */
import { readFileSync } from "node:fs";

const fix = JSON.parse(readFileSync("tests/fixtures/bbox-alignment.json", "utf8"));

// Kept in step with src/lib/bboxToScreen.ts BY HAND — the same hand-sync the
// module's own header warns about. A divergence here is itself a finding.
function bboxToScreen(bbox, page, renderWidth) {
  const [x0, y0, x1, y1] = bbox;
  const isRotated = page.rotation % 180 === 90;
  const Wpre = isRotated ? page.height : page.width;
  const Hpre = isRotated ? page.width : page.height;
  if (Wpre <= 0 || Hpre <= 0 || page.width <= 0) return null;
  let sx0, sy0, sx1, sy1;
  switch (((page.rotation % 360) + 360) % 360) {
    case 90:  sx0 = Hpre - y1; sy0 = x0; sx1 = Hpre - y0; sy1 = x1; break;
    case 180: sx0 = Wpre - x1; sy0 = Hpre - y1; sx1 = Wpre - x0; sy1 = Hpre - y0; break;
    case 270: sx0 = y0; sy0 = Wpre - x1; sx1 = y1; sy1 = Wpre - x0; break;
    default:  sx0 = x0; sy0 = y0; sx1 = x1; sy1 = y1; break;
  }
  const scale = renderWidth / page.width;
  return {
    left: Math.min(sx0, sx1) * scale,
    top: Math.min(sy0, sy1) * scale,
    width: Math.abs(sx1 - sx0) * scale,
    height: Math.abs(sy1 - sy0) * scale,
  };
}

/** The displayed page size, which is what a box must stay inside. */
function displayed(page, renderWidth) {
  const scale = renderWidth / page.width;
  return { w: page.width * scale, h: page.height * scale };
}

const ZOOMS = [380, 760, 1520];           // 3 zoom levels
const ROTATIONS = [0, 90, 180, 270];      // both rotations, and then some
const EPS = 1e-6;

let checks = 0, failures = [];
const fail = (m) => failures.push(m);

for (const rotation of ROTATIONS) {
  // PyMuPDF reports page.rect POST-rotation, so a rotated version of this sheet
  // would report its dimensions swapped. Modelled rather than ignored.
  const swap = rotation % 180 === 90;
  const page = {
    page: 1,
    width: swap ? fix.page.height : fix.page.width,
    height: swap ? fix.page.width : fix.page.height,
    rotation,
  };
  for (const renderWidth of ZOOMS) {
    const disp = displayed(page, renderWidth);

    for (const [i, bbox] of fix.bboxes.entries()) {
      const box = bboxToScreen(bbox, page, renderWidth);
      const id = `rot=${rotation} zoom=${renderWidth} bbox#${i}`;
      checks++;

      if (!box) { fail(`${id}: returned null`); continue; }

      // 1. Finite and non-negative extent.
      for (const k of ["left", "top", "width", "height"]) {
        if (!Number.isFinite(box[k])) fail(`${id}: ${k} is ${box[k]}`);
      }
      if (box.width < 0 || box.height < 0) fail(`${id}: negative extent`);

      // 2. CONTAINMENT. A highlight outside the rendered page is the visible
      //    failure mode — the box floats off the sheet or sits under it.
      const slack = 0.5; // sub-pixel, for float error only
      if (box.left < -slack || box.top < -slack) fail(`${id}: starts off-page`);
      if (box.left + box.width > disp.w + slack)
        fail(`${id}: runs past the right edge (${(box.left + box.width).toFixed(1)} > ${disp.w.toFixed(1)})`);
      if (box.top + box.height > disp.h + slack)
        fail(`${id}: runs past the bottom (${(box.top + box.height).toFixed(1)} > ${disp.h.toFixed(1)})`);

      // 3. AREA IS PRESERVED up to scale. Rotation must not stretch a box;
      //    a swapped axis would show up here as a changed aspect ratio.
      const scale = renderWidth / page.width;
      const pdfArea = Math.abs((bbox[2] - bbox[0]) * (bbox[3] - bbox[1]));
      const screenArea = box.width * box.height;
      const expected = pdfArea * scale * scale;
      if (expected > EPS && Math.abs(screenArea - expected) / expected > 1e-9)
        fail(`${id}: area ${screenArea.toFixed(2)} != ${expected.toFixed(2)}`);

      // 4. ZOOM IS LINEAR. Doubling the render width must double every
      //    coordinate — otherwise a box drifts off its feature as you zoom,
      //    which is exactly the "looks right at one zoom" failure.
      const half = bboxToScreen(bbox, page, renderWidth / 2);
      for (const k of ["left", "top", "width", "height"]) {
        if (Math.abs(box[k] - half[k] * 2) > 1e-6)
          fail(`${id}: ${k} not linear in zoom (${box[k]} vs ${half[k] * 2})`);
      }
    }
  }
}

// 5. ROTATION IS A BIJECTION. Applying all four rotations to the same box must
//    produce four DISTINCT placements (except where symmetry makes two equal),
//    and 0° must be the identity. If two rotations collide, one of them is
//    putting the highlight where the other belongs.
{
  const page0 = { page: 1, ...fix.page, rotation: 0 };
  for (const [i, bbox] of fix.bboxes.entries()) {
    const at0 = bboxToScreen(bbox, page0, page0.width);
    if (Math.abs(at0.left - bbox[0]) > EPS || Math.abs(at0.top - bbox[1]) > EPS)
      fail(`identity: bbox#${i} moved at rotation 0 and scale 1`);
  }
}

console.log(
  `bbox alignment: ${checks} transform checks ` +
  `(${fix.bboxes.length} boxes x ${ZOOMS.length} zooms x ${ROTATIONS.length} rotations)`,
);
console.log(`  sheet: ${fix.filename}`);
console.log(`  page:  ${fix.page.width}x${fix.page.height} rotation ${fix.page.rotation}`);

if (failures.length) {
  console.error(`\n✗ ${failures.length} alignment failure(s):\n  ` +
    failures.slice(0, 20).join("\n  ") +
    (failures.length > 20 ? `\n  …and ${failures.length - 20} more` : "") + "\n");
  process.exit(1);
}
console.log("✓ transform is contained, area-preserving, linear in zoom, identity at 0°");
console.log("  NOT checked here: that each bbox encloses the intended feature — that needs an eye.");
